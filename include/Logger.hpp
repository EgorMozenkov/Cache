#pragma once
#include <iostream>

/**
 * @brief Пространство имен для глобального логгера симулятора.
 */
namespace Log
{
    /**
     * @brief Уровни детализации вывода в консоль.
     */
    enum LogLevel { 
        ERROR,          ///< Критические ошибки (например, передача нулевого размера кэша).
        INFO,           ///< Базовая статистика (hit rate, результаты бенчмарков).
        TRACE,          ///< Детальная информация (состояние директорий и очередей).
        DEBUG           ///< Максимальная детализация (каждый хит/мисс, работа алгоритма).
    };

    extern LogLevel log_level;

    /**
     * @brief Устанавливает текущий порог логирования.
     * @param level Желаемый уровень (сообщения с уровнем выше заданного будут игнорироваться).
     * @return LogLevel Предыдущий уровень логирования.
     */
    LogLevel set_log_level(LogLevel level);


    /**
     * @brief Универсальная функция потокового вывода логов.
     * 
     * Использует C++17 fold expressions (выражения свертки) для безопасной 
     * распаковки произвольного количества аргументов и их вывода в std::cout 
     * без накладных расходов на рекурсивные вызовы шаблонов.
     * 
     * @tparam Args Пакет типов передаваемых аргументов.
     * @param level Уровень важности текущего сообщения.
     * @param args Аргументы для вывода (текст, числа, ключи).
     */
    template <typename ... Args>
    void trace(LogLevel level, const Args& ... args) 
    {
        if (level <= log_level) {
            (std::cout << ... << args);
        }
    }
}