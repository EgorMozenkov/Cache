/**
 * @brief Базовый интерфейс для всех алгоритмов кэша.
 * 
 * Задает единый стандарт для обработки запросов. Позволяет
 * создать любой алгоритм (LRU, LFU, ARC, LIRS) и прозрачно 
 * связывать их в многоуровневые системы (L0 -> L1 -> L2), где промахи 
 * верхнего уровня передаются на нижний.
 */

#pragma once

#include <vector>

/**
 * @brief Результат выполнения запроса к кэшу.
 */
template <typename Key>
struct CacheResult {
    bool hit;               ///< true, если элемент найден в кэше.
    bool has_evicted;       ///< true, если для освобождения места пришлось вытеснить другой элемент.
    Key evicted_key;        ///< Ключ вытесненного элемента (имеет смысл только если has_evicted == true).
};

template <typename Key>
class ICache {
    public:
    virtual ~ICache () = default;

    /**
     * @brief Обрабатывает запрос к элементу и обновляет внутреннюю статистику.
     * 
     * Если происходит промах (miss) и кэш заполнен, алгоритм самостоятельно 
     * определяет и вытесняет наименее ценный элемент согласно своей модели.
     * 
     * @param key Уникальный идентификатор запрашиваемого элемента.
     * @return CacheResult<Key> Структура с флагом попадания и данными о вытесненном ключе.
     */
    virtual CacheResult<Key> request (const Key& key) = 0;

    /**
     * @brief Проверяет наличие ключа в кэше без изменения статистики обращений.
     * @param key Искомый ключ.
     * @return true Если ключ находится на текущем уровне кэша.
     */
    virtual bool contains(const Key& key) = 0;

    /**
     * @brief Принудительно удаляет элемент из кэша.
     * @param key Ключ, который необходимо удалить.
     */
    virtual void erase(const Key& key) = 0;

    /**
     * @brief Возвращает список всех ключей, находящихся сейчас в кэше.
     * @return std::vector<Key> Массив ключей (используется для отладки и передачи состояния).
     */
    virtual std::vector<Key> get_elements() = 0;

    /**
     * @brief Выводит текущее состояние кэша в консоль (для отладки).
     */
    virtual void read_cache () = 0;
};